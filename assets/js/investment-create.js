// Keep creation feedback next to the original fields. HTMX does not swap
// validation errors; preserving the DOM also preserves the retry key.
(function () {
    function createForm(event) {
        var elt = event.detail && event.detail.elt;
        return elt && elt.closest ? elt.closest('form[data-investment-create]') : null;
    }

    document.addEventListener('htmx:beforeRequest', function (event) {
        var form = createForm(event);
        if (!form) return;
        form.setAttribute('aria-busy', 'true');
        form.querySelector('[data-investment-feedback]').hidden = true;
    });

    document.addEventListener('htmx:afterRequest', function (event) {
        var form = createForm(event);
        if (form) form.removeAttribute('aria-busy');
    });

    function showError(event, message) {
        var form = createForm(event);
        if (!form) return;
        var feedback = form.querySelector('[data-investment-feedback]');
        feedback.textContent = message;
        feedback.hidden = false;
        feedback.focus();
        // Do not replace the specific, persistent error with a generic toast.
        event.stopPropagation();
    }

    document.addEventListener('htmx:responseError', function (event) {
        var xhr = event.detail && event.detail.xhr;
        showError(event, xhr && xhr.responseText.trim() || 'Não foi possível registrar. Confira os dados e tente novamente.');
    }, true);

    document.addEventListener('htmx:sendError', function (event) {
        showError(event, 'Conexão interrompida. Confira o histórico antes de tentar novamente.');
    }, true);
}());

// Local to investments: integers typed here are reais, never a cents dial.
(function () {
    var rejected = new WeakSet();
    var openers = new WeakMap();
    var maxCents = BigInt('9223372036854775807');

    function rawAmount(value) { return value.trim().replace(/^R\$ /, '').trim(); }
    function amountState(value, complete, allowZero) {
        var raw = rawAmount(value);
        var valid = /^(?:[0-9]+|[1-9][0-9]{0,2}(?:\.[0-9]{3})+)(?:,[0-9]{1,2})?$/.test(raw);
        var editingComma = !complete && /^(?:[0-9]+|[1-9][0-9]{0,2}(?:\.[0-9]{3})+),$/.test(raw);
        if (!valid && !editingComma) return { value: raw === '' ? '' : value, valid: raw === '' };
        var parts = raw.replace(/\./g, '').split(',');
        var cents = BigInt(parts[0]) * BigInt(100) + BigInt((parts[1] || '').padEnd(2, '0'));
        if (cents > maxCents || (!allowZero && cents === BigInt(0))) return { value: value, valid: false };
        var integer = parts[0].replace(/^0+(?=\d)/, '').replace(/\B(?=(\d{3})+(?!\d))/g, '.');
        var decimal = complete ? ',' + (parts[1] || '').padEnd(2, '0') : (parts.length > 1 ? ',' + parts[1] : '');
        return { value: 'R$ ' + integer + decimal, valid: valid, editing: editingComma };
    }

    function formatField(el, event, complete) {
        var before = el.value;
        var cursor = el.selectionStart;
        var end = el.selectionEnd;
        var significant = function (value) { return (value.match(/[0-9,]/g) || []).length; };
        var offset = significant(before.slice(0, cursor));
        var endOffset = significant(before.slice(0, end));
        var isEdit = event && (event.inputType === 'insertText' || /^delete/.test(event.inputType || ''));
        var raw = before;
        // Remove only the grouping generated by this mask during ordinary edits.
        // Pasted / previously rejected text keeps strict BR grouping validation.
        if (isEdit && !rejected.has(el) && event.data !== '.') raw = raw.replace(/\./g, '');
        var state = amountState(raw, complete, el.dataset.investmentMoney === 'zero');
        el.setCustomValidity(state.valid ? '' : 'Use um valor em reais, com até duas casas decimais (ex.: R$ 1.234,56).');
        if (!state.valid && !state.editing) rejected.add(el);
        else if (state.valid || raw === '') rejected.delete(el);
        el.value = state.value;
        if (!complete && state.value !== before && cursor !== null) {
            function position(count) {
                if (!count) return Math.min(3, state.value.length);
                var seen = 0;
                for (var i = 0; i < state.value.length; i++) {
                    if (/[0-9,]/.test(state.value[i]) && ++seen === count) return i + 1;
                }
                return state.value.length;
            }
            el.setSelectionRange(position(offset), position(endOffset));
        }
    }

    document.addEventListener('input', function (event) {
        var el = event.target;
        if (!el || !el.matches) return;
        if (el.matches('[data-investment-money]')) formatField(el, event, false);
        if (el.matches('[data-investment-search]')) {
            var query = el.value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLocaleLowerCase('pt-BR').trim();
            var visible = 0;
            document.querySelectorAll('[data-investment-row]').forEach(function (row) {
                var text = row.querySelector('.investment-identity').textContent.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLocaleLowerCase('pt-BR');
                row.hidden = !text.includes(query);
                if (!row.hidden) visible++;
            });
            document.querySelector('[data-investment-search-empty]').hidden = visible !== 0;
        }
    });
    document.addEventListener('blur', function (event) {
        if (event.target.matches && event.target.matches('[data-investment-money]')) formatField(event.target, null, true);
    }, true);

    // The select filters on its own once scripting is on; the submit button
    // remains as the no-JS path.
    document.querySelectorAll('[data-investment-filter-submit]').forEach(function (el) { el.hidden = true; });
    document.addEventListener('change', function (event) {
        var el = event.target;
        if (!el || !el.matches || !el.matches('[data-investment-filter]') || !el.form) return;
        if (el.form.requestSubmit) el.form.requestSubmit();
        else el.form.submit();
    });

    function openPanel(panel, opener) {
        if (!panel) return;
        document.querySelectorAll('[data-investment-panel][open]').forEach(function (other) { other.close(); });
        openers.set(panel, opener);
        panel.showModal();
        var field = panel.querySelector('[data-investment-feedback]:not([hidden]), input:not([type="hidden"]), select');
        if (field) field.focus();
    }
    document.addEventListener('click', function (event) {
        var opener = event.target.closest('[data-investment-open]');
        if (opener) openPanel(document.getElementById(opener.dataset.investmentOpen), opener);
        var closer = event.target.closest('[data-investment-close]');
        if (closer) closer.closest('dialog').close();
        if (event.target.matches('dialog[data-investment-panel]')) {
            var rect = event.target.getBoundingClientRect();
            if (event.clientX < rect.left || event.clientX > rect.right || event.clientY < rect.top || event.clientY > rect.bottom) event.target.close();
        }
    });
    document.querySelectorAll('[data-investment-panel]').forEach(function (panel) {
        panel.addEventListener('close', function () {
            var opener = openers.get(panel);
            if (opener && opener.isConnected) opener.focus();
        });
    });
    document.querySelectorAll('[data-investment-money]').forEach(function (el) { formatField(el, null, true); });
    document.querySelectorAll('[data-investment-search-control]').forEach(function (el) { el.hidden = false; });
    var failedPanel = document.querySelector('[data-investment-reopen]');
    if (failedPanel) openPanel(failedPanel, document.querySelector('[data-investment-open]'));

    // Lifecycle/edit errors stay within the currently open form, as creation
    // errors already do above. No swap means entered values and focus survive.
    document.addEventListener('htmx:responseError', function (event) {
        var el = event.detail && event.detail.elt;
        var form = el && el.closest('form[data-investment-operation]');
        if (!form || form.hasAttribute('data-investment-create')) return;
        var feedback = form.querySelector('[data-investment-operation-feedback]');
        if (!feedback) {
            feedback = document.createElement('p');
            feedback.dataset.investmentOperationFeedback = '';
            feedback.className = 'investment-feedback';
            feedback.setAttribute('role', 'alert');
            feedback.tabIndex = -1;
            form.prepend(feedback);
        }
        feedback.hidden = false;
        feedback.textContent = event.detail.xhr.responseText.trim() || 'Não foi possível salvar. Confira os dados e tente novamente.';
        feedback.focus();
        event.stopPropagation();
    }, true);
}());
